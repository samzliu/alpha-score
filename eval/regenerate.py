"""Rebuild eval/RESULTS.md from the scored files in eval/data/ (no API calls).

    python eval/regenerate.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from evaluate import CLASSES, report, summary  # noqa: E402

D = os.path.join(HERE, "data")
# (name, main file, restyle file or None)
MODELS = [
    ("**GLM-5.3-Flash** (Fireworks pay-per-token; default)", "glm53flash_main", "glm53flash_restyle"),
    ("GLM-5.3-Flash, second run (noise check)", "glm53flash_main_rerun", None),
    ("GLM-5.3-Flash, both runs averaged (= `--repeats 2`)", "glm53flash_main_avg2", None),
    ("Qwen2.5-72B base", "qwen72b_main", "qwen72b_restyle"),
    ("Qwen2.5-72B instruct", "qwen72b_instruct_main", "qwen72b_instruct_restyle"),
    ("Qwen2.5-7B base", "qwen7b_main", None),
    ("Qwen2.5-7B instruct", "qwen7b_instruct_main", None),
    ("gpt-oss-120b (Fireworks pay-per-token; fails)", "gptoss120b_main", None),
]

PREAMBLE = """# Benchmark results

Generated by `python eval/regenerate.py` from the scored files in `eval/data/` (uses `eval/evaluate.py`; no API
calls). To add a model, score the benchmark with it (`alpha-score score eval/data/chunks_main.jsonl --model <key>
--json` or `Scorer().score_rows(...)`, saving one JSON line per passage), then add the file to `MODELS` in
`eval/regenerate.py`.

**Benchmark** (`eval/data/chunks_main.jsonl`): 50 documents, 608 passages of about 100 words each.
- **high (17):** three hand-picked blog posts. These are thejauntwriting "You Need to Be Drinking So Much Coffee",
  verkish "What's up with Gefilte Fish?" and Goodfire "Neural Networks Are Already Clean". The rest are 14 Atlantic
  essays published Oct 20–21, 2026, after the reference models' training data.
- **claude (17):** Claude Opus essays from a one-line prompt. Each matches a high document's topic or title.
- **wiki (6):** Wikipedia articles on the same topics.
- **crank (6):** conspiracy and misinformation Substack posts from 3 authors, Sep–Oct 2026.
- **gib (4):** random characters, word salad, bigram Markov text, and word-shuffled high-alpha passages.

**2×2 test** (`eval/data/chunks_restyle.jsonl`): for 16 topics, Claude Opus rewrote the high-alpha text in its own
voice while keeping every idea. It also rewrote its own same-topic essay in the human author's voice, imitating a
600-word sample.

**Provenance.**
- The GLM-5.3-Flash and gpt-oss-120b files were produced with this package's API client against Fireworks'
  pay-per-token API on 2026-10-22 and 2026-10-23.
- The Qwen files come from vLLM on Modal: either `scripts/modal_backend.py` or the original research scripts, whose
  math the package copies verbatim. On 7B, the packaged backend reproduced the research scripts' target-token NLLs
  exactly on all 608 passages.
- All runs score the text raw, with no chat template, including the instruct models.
- The gate is coherence < 2.5. An earlier version also gated on conv < −2.5; dropping it changed no result below
  except the noise-check run, where it had gated one crank post.

## Summary

AUROC = probability that a random high-alpha document outscores a random document of the other class (gated
documents count as lowest).
"""


def main():
    rows = ["| reference model | vs " + " | vs ".join(CLASSES) + " | vs all | gib gated / real gated | 2×2 content / voice |",
            "|---|" + "---|" * (len(CLASSES) + 3)]
    sections = []
    for name, main_f, rs_f in MODELS:
        m, r = os.path.join(D, main_f + ".jsonl"), os.path.join(D, rs_f + ".jsonl") if rs_f else ""
        s = summary(m, r)
        cv = f"{s['content']:+.2f} / {s['voice']:+.2f}" if r else "not run"
        rows.append(f"| {name} | " + " | ".join(f"{s[c]:.2f}" for c in CLASSES) +
                    f" | {s['all']:.2f} | {s['gib_gated']}/4 / {s['real_gated']}/{s['n_real']} | {cv} |")
        sections.append(report(m, r, name.replace("**", "")))
    text = PREAMBLE + "\n" + "\n".join(rows) + "\n\n" + "\n".join(sections)
    open(os.path.join(HERE, "RESULTS.md"), "w").write(text)
    print("\n".join(rows))


if __name__ == "__main__":
    main()
